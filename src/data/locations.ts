export function projectSite(lat: number, lng: number): { x: number; y: number } {
  const x = ((lng + 124.8) / 58.5) * 100;
  const y = ((49.2 - lat) / 25.2) * 100;
  return {
    x: Math.min(96, Math.max(4, x)),
    y: Math.min(92, Math.max(6, y)),
  };
}

